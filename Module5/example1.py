rounds = int(input("How many greetings: "))
finished_rounds = 0
while finished_rounds<rounds:
    print("Good morning")
    finished_rounds = finished_rounds + 1

# User inputs how many greetings they would like printed, the code loops and adds a 1 onto the finished_rounds
# which is part of the loop, when that number reaches the number input by the user, the loop ends.

# If the loop is on a counter within thr code, we use indented "counter = counter + 1" to increase the counter per loop
